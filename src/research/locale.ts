export type ResearchMessage = keyof typeof messages;

export function researchMessage(key: ResearchMessage, language: ResearchLanguage = 'es') {
  return messages[key][language === 'en' ? 1 : 0];
}

export class ResearchError extends Error {
  code: ResearchMessage;

  constructor(code: ResearchMessage) {
    super(researchMessage(code));
    this.code = code;
  }
}
