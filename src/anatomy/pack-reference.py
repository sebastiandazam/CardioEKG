"""Convert the HeartDeformNets wh_template.vtp to the local viewer format.

The source is pinned and identified in ATTRIBUTION.md. Uses only the standard
library. Output stores original labeled triangles with quantized positions.
"""
from argparse import ArgumentParser
from base64 import b64decode, b64encode
from pathlib import Path
from struct import pack, unpack_from
from xml.etree import ElementTree as ET
from zlib import decompress


def read_array(encoded, element, format_code):
    start = int(element.get("offset"))
    chunks, block_size, tail_size = unpack_from("<3I", b64decode(encoded[start:start + 16]))
    if not chunks:
        return ()
    header_length = ((3 + chunks) * 4 + 2) // 3 * 4
    lengths = unpack_from(f"<{chunks}I", b64decode(encoded[start:start + header_length]), 12)
    payload_start = start + header_length
    payload_end = payload_start + ((sum(lengths) + 2) // 3) * 4
    raw = b64decode(encoded[payload_start:payload_end])
    cursor = 0
    output = []
    for length in lengths:
        output.append(decompress(raw[cursor:cursor + length]))
        cursor += length
    data = b"".join(output)
    assert len(data) == (chunks - 1) * block_size + (tail_size or block_size)
    return unpack_from(f"<{len(data) // 8}{format_code}", data)


def convert(path):
    root = ET.parse(path).getroot()
    piece = root.find("PolyData/Piece")
    encoded = root.find("AppendedData").text.strip()[1:]
    regions = read_array(encoded, piece.find("PointData/DataArray"), "d")
    positions = read_array(encoded, piece.find("Points/DataArray"), "d")
    indices = read_array(encoded, piece.find("Polys/DataArray[@Name='connectivity']"), "q")
    offsets = read_array(encoded, piece.find("Polys/DataArray[@Name='offsets']"), "q")
    assert len(regions) == 22_827 and len(offsets) == 45_626
    assert all(offset == 3 * (i + 1) for i, offset in enumerate(offsets))
    assert all(0 <= value <= 1 for value in positions)
    groups = [[] for _ in range(7)]
    for offset in range(0, len(indices), 3):
        triangle = indices[offset:offset + 3]
        labels = {int(regions[index]) for index in triangle}
        assert len(labels) == 1
        groups[labels.pop() - 1].extend(triangle)
    yield pack("<II", len(regions), len(groups))
    yield pack(f"<{len(positions)}H", *(round(value * 65_535) for value in positions))
    for group in groups:
        yield pack("<I", len(group))
        yield pack(f"<{len(group)}H", *group)


if __name__ == "__main__":
    parser = ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    encoded = b64encode(b"".join(convert(args.source))).decode()
    output = (
        "// Derived from HeartDeformNets wh_template.vtp (Apache-2.0). See ATTRIBUTION.md.\n"
        "// Generated by pack-reference.py.\n"
        f"export const cardiacReference = '{encoded}'\n"
    )
    args.output.write_text(output)
